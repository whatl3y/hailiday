import type { Kysely } from 'kysely';
import {
  ACTIVATION_STATES,
  ASSET_POLICY_SUBJECT_KINDS,
  ASSET_POLICY_USE_STATES,
  BLOCKED_ADDRESS_SOURCES,
  BUILDING_FORMS,
  COORDS_SOURCES,
  DISPLAY_ADDRESS_BASES,
  ENTRY_METHODS,
  HOLIDAY_IDS,
  LIGHTING_MODES,
  MATCH_CLASSES,
  PEOPLE_RESOLUTIONS,
  PERMISSION_EVALUATION_CONTEXTS,
  PIPELINE_STAGES,
  PRECISION_SOURCES,
  PRECISIONS,
  PROJECT_KINDS,
  QUALITY_HINTS,
  ROOM_TYPES,
  SCENE_TYPES,
  SKIP_REASONS,
  SOURCE_ASSET_STATES,
  SOURCE_KINDS,
  STREET_VIEW_SOURCE_MODES,
  STYLES,
  UPLOAD_DECLINE_CODES,
  UPLOAD_DECLINE_REASON_CLASSES,
  UPLOAD_DECLINE_REASONS,
} from '@hailiday/core';
import {
  ID_AND_CREATED,
  ID_CREATED_UPDATED,
  checkIn,
  checkSubset,
  runStatements,
  updatedAtTrigger,
} from '../sql-helpers.js';

const useState = (column: string) =>
  `${column} text NOT NULL DEFAULT 'unknown' ${checkIn(column, ASSET_POLICY_USE_STATES)}`;

/** Properties, projects, discovery runs, source assets, asset policies and evaluations. */
export async function up(db: Kysely<unknown>): Promise<void> {
  await runStatements(db, [
    `CREATE TABLE properties (
      ${ID_CREATED_UPDATED},
      owner_id uuid NOT NULL REFERENCES owners(id) ON DELETE CASCADE,
      place_id text NOT NULL,
      place_id_refreshed_at timestamptz NOT NULL,
      country_code char(2) NOT NULL,
      entry_method text NOT NULL ${checkIn('entry_method', ENTRY_METHODS)},
      precision text NOT NULL ${checkIn('precision', PRECISIONS)},
      precision_source text NOT NULL ${checkIn('precision_source', PRECISION_SOURCES)},
      partial_match boolean NOT NULL,
      place_types text[] NOT NULL,
      multi_unit boolean NOT NULL,
      unit_designation text,
      geometry_available boolean NOT NULL,
      facade_width_m numeric(6,2),
      entrance_offset_m numeric(6,2),
      road_bearing_deg numeric(5,2),
      display_loads_issued smallint NOT NULL DEFAULT 0 CHECK (display_loads_issued >= 0),
      owner_blur_detected_at timestamptz,
      target_lat numeric(9,6),
      target_lng numeric(9,6),
      coords_source text ${checkIn('coords_source', COORDS_SOURCES)},
      coords_expire_at timestamptz,
      display_address text,
      display_address_basis text ${checkIn('display_address_basis', DISPLAY_ADDRESS_BASES)},
      display_address_stored_at timestamptz,
      manual_entry jsonb,
      CONSTRAINT properties_transient_display_address_rule CHECK (
        display_address IS NULL OR display_address_basis IS DISTINCT FROM 'autocomplete_transient'
      )
    )`,
    updatedAtTrigger('properties'),
    `CREATE INDEX properties_owner_place_idx ON properties (owner_id, place_id)`,
    `CREATE INDEX properties_coords_expire_at_idx ON properties (coords_expire_at)`,

    `CREATE TABLE projects (
      ${ID_CREATED_UPDATED},
      owner_id uuid NOT NULL REFERENCES owners(id) ON DELETE CASCADE,
      kind text NOT NULL ${checkIn('kind', PROJECT_KINDS)},
      property_id uuid REFERENCES properties(id),
      project_version integer NOT NULL DEFAULT 0 CHECK (project_version >= 0),
      active_source_asset_id uuid,
      scene_type text ${checkIn('scene_type', SCENE_TYPES)},
      building_form text ${checkIn('building_form', BUILDING_FORMS)},
      room_type text ${checkIn('room_type', ROOM_TYPES)},
      holiday_id text NOT NULL ${checkIn('holiday_id', HOLIDAY_IDS)},
      style text NOT NULL DEFAULT 'classic' ${checkIn('style', STYLES)},
      lighting_mode text NOT NULL DEFAULT 'source' ${checkIn('lighting_mode', LIGHTING_MODES)},
      saved_at timestamptz,
      last_activity_at timestamptz NOT NULL,
      expires_at timestamptz,
      preservation_hold_id uuid REFERENCES preservation_holds(id),
      deleted_at timestamptz,
      CONSTRAINT projects_address_property_rule CHECK (kind <> 'address' OR property_id IS NOT NULL)
    )`,
    updatedAtTrigger('projects'),
    `CREATE INDEX projects_owner_activity_idx ON projects (owner_id, last_activity_at)`,
    `CREATE INDEX projects_owner_created_idx ON projects (owner_id, created_at)`,
    `CREATE INDEX projects_last_activity_at_idx ON projects (last_activity_at)`,
    `CREATE INDEX projects_expires_at_idx ON projects (expires_at)`,
    `CREATE INDEX projects_property_id_idx ON projects (property_id)`,

    `CREATE TABLE source_discoveries (
      ${ID_CREATED_UPDATED},
      project_id uuid NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
      project_version integer NOT NULL,
      entry_method text NOT NULL ${checkIn('entry_method', ENTRY_METHODS)},
      match_class text NOT NULL ${checkIn('match_class', MATCH_CLASSES)},
      reason text ${checkIn('reason', SKIP_REASONS)},
      retryable boolean NOT NULL DEFAULT false,
      source_mode text NOT NULL ${checkIn('source_mode', STREET_VIEW_SOURCE_MODES)},
      thresholds_version text NOT NULL,
      algorithm_version text NOT NULL,
      candidates jsonb NOT NULL DEFAULT '[]'::jsonb,
      signals jsonb NOT NULL DEFAULT '{}'::jsonb,
      provider_calls jsonb NOT NULL DEFAULT '{}'::jsonb,
      duration_ms integer NOT NULL CHECK (duration_ms >= 0),
      UNIQUE (project_id, project_version),
      CONSTRAINT source_discoveries_reason_rule CHECK (match_class <> 'skip_to_upload' OR reason IS NOT NULL),
      CONSTRAINT source_discoveries_retryable_rule CHECK (NOT retryable OR reason = 'error')
    )`,
    updatedAtTrigger('source_discoveries'),

    `CREATE TABLE asset_policies (
      ${ID_CREATED_UPDATED},
      subject_kind text NOT NULL ${checkIn('subject_kind', ASSET_POLICY_SUBJECT_KINDS)},
      subject_id uuid NOT NULL,
      ${useState('display')},
      ${useState('store')},
      ${useState('ai_process')},
      ${useState('edit')},
      ${useState('distribute_derivative')},
      ${useState('commerce_adjacent')},
      train text NOT NULL DEFAULT 'denied' CHECK (train = 'denied'),
      evidence_ref text NOT NULL,
      license_version text,
      territory text,
      attribution_text text,
      expires_at timestamptz,
      revoked_at timestamptz,
      created_by text NOT NULL
    )`,
    updatedAtTrigger('asset_policies'),
    `CREATE INDEX asset_policies_subject_idx ON asset_policies (subject_kind, subject_id)`,

    `CREATE TABLE source_assets (
      ${ID_CREATED_UPDATED},
      owner_id uuid NOT NULL REFERENCES owners(id) ON DELETE CASCADE,
      project_id uuid NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
      kind text NOT NULL ${checkIn('kind', SOURCE_KINDS)},
      state text NOT NULL ${checkIn('state', SOURCE_ASSET_STATES)},
      derived_from_source_asset_id uuid REFERENCES source_assets(id) ON DELETE SET NULL,
      object_key text,
      checksum_sha256 text,
      content_type text,
      byte_length bigint,
      width integer,
      height integer,
      original_format text,
      original_byte_length bigint,
      original_width integer,
      original_height integer,
      orientation_applied smallint CHECK (orientation_applied BETWEEN 1 AND 8),
      client_prepared boolean,
      capture_date text CHECK (capture_date ~ '^[0-9]{4}(-(0[1-9]|1[0-2]))?$'),
      copyright text,
      is_google_imagery boolean,
      street_view_mode text ${checkIn('street_view_mode', STREET_VIEW_SOURCE_MODES)},
      viewpoint jsonb,
      viewpoint_key text GENERATED ALWAYS AS (
        (viewpoint ->> 'panoId') || '|' || (viewpoint ->> 'heading') || '|' ||
        (viewpoint ->> 'pitch') || '|' || (viewpoint ->> 'fov') || '|' ||
        (viewpoint ->> 'width') || '|' || (viewpoint ->> 'height')
      ) STORED,
      attestation_version text,
      attested_at timestamptz,
      scene_type text ${checkIn('scene_type', SCENE_TYPES)},
      building_form text ${checkIn('building_form', BUILDING_FORMS)},
      room_type text ${checkIn('room_type', ROOM_TYPES)},
      scene_type_confidence numeric(4,3) CHECK (scene_type_confidence BETWEEN 0 AND 1),
      scene_type_corrected boolean NOT NULL DEFAULT false,
      multi_unit_facade boolean,
      people_detected boolean NOT NULL DEFAULT false,
      people_boxes jsonb,
      suggested_crop_box jsonb,
      people_resolution text ${checkIn('people_resolution', PEOPLE_RESOLUTIONS)},
      crop_box jsonb,
      private_only boolean NOT NULL DEFAULT false,
      quality_hints text[] NOT NULL DEFAULT '{}' ${checkSubset('quality_hints', QUALITY_HINTS)},
      existing_decorations jsonb,
      season_cues jsonb,
      screening jsonb,
      hold_for_review boolean NOT NULL DEFAULT false,
      declined_code text ${checkIn('declined_code', UPLOAD_DECLINE_CODES)},
      declined_reason_class text ${checkIn('declined_reason_class', UPLOAD_DECLINE_REASON_CLASSES)},
      declined_reason text ${checkIn('declined_reason', UPLOAD_DECLINE_REASONS)},
      provider_refused_at timestamptz,
      ready_at timestamptz,
      asset_policy_id uuid REFERENCES asset_policies(id) ON DELETE SET NULL,
      revalidated_at timestamptz,
      stale_at timestamptz,
      expires_at timestamptz,
      preservation_hold_id uuid REFERENCES preservation_holds(id),
      deleted_at timestamptz,
      CONSTRAINT source_assets_upload_people_resolution_rule CHECK (
        kind <> 'upload' OR people_resolution IS NOT NULL
      ),
      CONSTRAINT source_assets_private_only_rule CHECK (
        people_resolution IS DISTINCT FROM 'kept' OR private_only
      )
    )`,
    updatedAtTrigger('source_assets'),
    `CREATE INDEX source_assets_owner_id_idx ON source_assets (owner_id)`,
    `CREATE INDEX source_assets_project_id_idx ON source_assets (project_id)`,
    `CREATE INDEX source_assets_expires_at_idx ON source_assets (expires_at)`,
    `CREATE INDEX source_assets_checksum_idx ON source_assets (checksum_sha256)`,
    `CREATE UNIQUE INDEX source_assets_project_viewpoint_key_idx ON source_assets (project_id, viewpoint_key)
      WHERE kind = 'street_view'`,

    `ALTER TABLE projects ADD CONSTRAINT projects_active_source_asset_id_fkey
      FOREIGN KEY (active_source_asset_id) REFERENCES source_assets(id) ON DELETE SET NULL`,

    `CREATE TABLE permission_evaluations (
      ${ID_AND_CREATED},
      source_asset_id uuid REFERENCES source_assets(id) ON DELETE CASCADE,
      asset_policy_id uuid NOT NULL REFERENCES asset_policies(id),
      context text NOT NULL ${checkIn('context', PERMISSION_EVALUATION_CONTEXTS)},
      job_id uuid,
      attempt_id uuid,
      stage text ${checkIn('stage', PIPELINE_STAGES)},
      result jsonb NOT NULL,
      capability_state text NOT NULL ${checkIn('capability_state', ACTIVATION_STATES)},
      evaluated_at timestamptz NOT NULL
    )`,
    `CREATE INDEX permission_evaluations_source_asset_id_idx ON permission_evaluations (source_asset_id)`,
    `CREATE INDEX permission_evaluations_asset_policy_id_idx ON permission_evaluations (asset_policy_id)`,

    `CREATE TABLE blocked_addresses (
      ${ID_CREATED_UPDATED},
      place_id text NOT NULL UNIQUE,
      normalized_address_hash text,
      source text NOT NULL ${checkIn('source', BLOCKED_ADDRESS_SOURCES)},
      report_id uuid,
      evidence_ref text NOT NULL,
      created_by uuid REFERENCES users(id) ON DELETE SET NULL,
      expires_at timestamptz,
      removed_at timestamptz
    )`,
    updatedAtTrigger('blocked_addresses'),
    `CREATE INDEX blocked_addresses_normalized_address_hash_idx ON blocked_addresses (normalized_address_hash)`,
  ]);
}
